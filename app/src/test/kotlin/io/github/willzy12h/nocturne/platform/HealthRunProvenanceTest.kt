/** R4: provenance is generated by the real owner, never inferred from an ENDED label. */
@RunWith(RobolectricTestRunner::class) @Config(sdk = [34])
class HealthRunProvenanceTest : PlatformGraphFixture() {
    private val context: Context = RuntimeEnvironment.getApplication()
    private suspend fun setup(demo: Boolean = false): Graph {
        lateinit var graph: Graph
        graph = fresh { Graph(context, DemoBedJet(now = { graph.now() })) }
        graph.clock = Clock.fixed(Instant.parse("2026-10-26T22:30:00Z"), ZoneOffset.UTC)
        graph.repository.updateSettings { it.copy(demoMode = demo, targetDevice = "ble:AA:BB:CC:DD:EE:FF") }
        graph.actions.confirmMs = 1
        return graph
    }
    private fun json(record: NightRecord) = BackupCodec.json.encodeToJsonElement(NightRecord.serializer(), record).jsonObject

    @Test fun aReceiptConfirmedRealProgrammePersistsItsExportProvenance() = runBlocking {
        val graph = setup()
        graph.actions.perform(Command.START_NIGHT, graph.repository.profiles.value.first().id)
        assertEquals(Confidence.CONFIRMED, graph.repository.activeNight.value?.confidence)
        val record = graph.repository.history.value.single()
        assertEquals("Health export needs explicit receipt-derived proof persisted with History", true,
            json(record)["bedJetRunConfirmed"]?.jsonPrimitive?.booleanOrNull)
        assertNull(json(record)["confirmedCompletionAt"]?.jsonPrimitive?.contentOrNull)
    }

    @Test fun naturalCompletionPersistsProofOnlyForTheConfirmedProgramme() = runBlocking {
        val graph = setup()
        graph.actions.perform(Command.START_NIGHT, graph.repository.profiles.value.first().id)
        val night = graph.repository.activeNight.value!!
        graph.clock = Clock.fixed(ZonedDateTime.parse(night.endsAt).toInstant(), ZoneOffset.UTC)
        assertTrue(graph.actions.expire(night.identity))
        assertEquals(night.endsAt,
            json(graph.repository.history.value.single())["confirmedCompletionAt"]?.jsonPrimitive?.contentOrNull)
    }

    @Test fun anUnknownProgrammeNeverAcquiresCompletionProofFromAClockOrEndedLabel() = runBlocking {
        val graph = setup()
        graph.actions.perform(Command.START_NIGHT, graph.repository.profiles.value.first().id)
        val unknown = graph.repository.activeNight.value!!.copy(confidence = Confidence.UNKNOWN)
        graph.repository.setActiveNight(unknown)
        graph.clock = Clock.fixed(ZonedDateTime.parse(unknown.endsAt).toInstant(), ZoneOffset.UTC)
        graph.actions.finish(unknown, EventKind.ENDED, "Clock elapsed")
        assertNull(json(graph.repository.history.value.single())["confirmedCompletionAt"]?.jsonPrimitive?.contentOrNull)
    }

    @Test fun localStopTrackingDoesNotClaimACompletedProgramme() = runBlocking {
        val graph = setup()
        graph.actions.perform(Command.START_NIGHT, graph.repository.profiles.value.first().id)
        graph.actions.perform(Command.STOP_TRACKING)
        assertNull(json(graph.repository.history.value.single())["confirmedCompletionAt"]?.jsonPrimitive?.contentOrNull)
    }

    @Test fun healthWritePermissionIsDeclaredForTheExplicitPermissionRequest() {
        @Suppress("DEPRECATION")
        val permissions = context.packageManager.getPackageInfo(context.packageName, PackageManager.GET_PERMISSIONS).requestedPermissions.orEmpty()
        assertTrue("Writing must use the explicit Health Connect write permission", "android.permission.health.WRITE_SLEEP" in permissions)
    }
}
